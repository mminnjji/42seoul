#include "libft.h"

int	pass_idx(char *str, int *i)
{
	int	tmp;

	tmp = *i;
	if (str[*i] == '\'')
	{
		while (str[*i] == '\'')
			(*i)++;
		if (str[*i] == '\"')
			(*i) = (*i) + 2;
		while (str[*i] != '\'')
			(*i)++;
		while (str[*i] == '\'')
			(*i)++;
	}
	else if (str[*i] == '\"')
	{
		while (str[*i] == '\"')
			(*i)++;
		while (str[*i] != '\"')
			(*i)++;
		while (str[*i] == '\"')
			(*i)++;
	}
	return ((*i) - 1 - tmp);
}
